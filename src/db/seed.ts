export async function seedInitialData(database: GramBillDB): Promise<void> {
  await database.transaction(
    'rw',
    database.shopSettings,
    database.products,
    database.customers,
    database.stockMovements,
    async () => {
      const existingSettings = await database.shopSettings.count();
      if (existingSettings > 0) {
        return;
      }

      const now = nowIso();

      const settings: ShopSettings = {
        id: LOCAL_SHOP_ID,
        shopId: LOCAL_SHOP_ID,
        deviceId: LOCAL_DEVICE_ID,
        createdAt: now,
        updatedAt: now,
        syncStatus: 'synced',
        shopName: 'Shree Electronics & Electricals',
        ownerName: 'Rakesh Kumar',
        phone: '9876500000',
        address: 'Main Market, Nandpur, District Bhadohi, Uttar Pradesh - 221401',
        gstin: '',
        upiId: 'shopowner@upi',
        upiPayeeName: 'Shree Electronics',
        invoicePrefix: 'INV-2026-',
        nextInvoiceNumber: 1,
        defaultPrintSize: 'thermal_80mm',
        languageMode: 'en',
        termsAndConditions:
          '1. Goods once sold will not be taken back. 2. Warranty as per manufacturer policy. 3. Please keep this bill for warranty claims.',
      };

      const products = PRODUCT_SEEDS.map((seed) => createProduct(seed, now));
      const customers = CUSTOMER_SEEDS.map((seed) =>
        createCustomer(seed, now),
      );
      const stockMovements: StockMovement[] = products.map((product) => ({
        id: newId(),
        shopId: LOCAL_SHOP_ID,
        deviceId: LOCAL_DEVICE_ID,
        createdAt: now,
        updatedAt: now,
        syncStatus: 'synced',
        productId: product.id,
        changeType: 'opening_stock',
        qtyChange: product.stockQty,
        referenceId: 'seed-opening-stock',
      }));

      await database.shopSettings.add(settings);
      await database.products.bulkAdd(products);
      await database.customers.bulkAdd(customers);
      await database.stockMovements.bulkAdd(stockMovements);
    },
  );
}
